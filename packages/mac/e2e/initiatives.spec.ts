const sidebar = (page: Page) => page.getByRole('navigation', { name: 'Sidebar' });
const shots = process.env.INITIATIVE_SHOTS;
const shot = async (page: Page, name: string): Promise<void> => {
  if (shots) await page.screenshot({ path: path.join(shots, name) });
};

const openInitiative = async (page: Page, name: string): Promise<void> => {
  await page.goto('/');
  await expect(sidebar(page)).toBeVisible();
  await sidebar(page).getByRole('button', { name: 'All Initiatives' }).click();
  await page.getByRole('button', { name: `Open ${name}` }).click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
};

const openArea = async (page: Page, name: string): Promise<void> => {
  await page.getByRole('tablist', { name: /^Areas of / }).getByRole('tab', { name: new RegExp(`^${name}`) }).click();
};

